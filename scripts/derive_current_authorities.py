# ── checks — each returns a list of problems; empty means sound ────────────

def _pin_problems(text: str) -> list[str]:
    """The guard's pin rule, applied before writing: in range, non-blank, names its symbol."""
    path_noise = {m for path, _s, _e in PIN_RE.findall(text) for m in IDENT_RE.findall(path)}
    problems: list[str] = []
    pins = checkable = 0
    for page_line, raw in enumerate(text.splitlines(), 1):
        found = PIN_RE.findall(raw)
        if not found:
            continue
        spans = [s for s in re.findall(r"`([^`]+)`", raw) if not PIN_RE.fullmatch(f"`{s}`")]
        expected = {m for s in spans for m in IDENT_RE.findall(s)} - path_noise
        for path, start, end in found:
            pins += 1
            f = REPO / path
            if not f.exists():
                problems.append(f"{path}:{start} — no such file (page line {page_line})")
                continue
            lines = f.read_text(encoding="utf-8").splitlines()
            lo, hi = int(start), int(end) if end else int(start)
            if lo < 1 or hi > len(lines) or hi < lo:
                problems.append(f"{path}:{start} — out of range (page line {page_line})")
                continue
            if not lines[lo - 1].strip():
                problems.append(f"{path}:{start} — the pinned line is blank")
                continue
            if not expected:
                continue
            checkable += 1
            window = " ".join(lines[max(0, lo - 1 - PIN_WINDOW):hi + PIN_WINDOW])
            if not any(name in window for name in expected):
                problems.append(f"{path}:{start} — none of {sorted(expected)} within "
                                f"±{PIN_WINDOW} lines (page line {page_line})")
    if pins < 30 or checkable < 15:
        problems.append(f"only {pins} pins / {checkable} content-checkable — the pin grammar "
                        "drifted and the check has gone vacuous")
    return problems


def _matrix_problems(precedence) -> list[str]:
    """`PRECEDENCE` against the arbiter's own branches, and against the arbiter driven."""
    sys.path.insert(0, str(REPO))
    from wisp.core.goal import GoalState, TerminalOutcome, derive_goal_state

    problems: list[str] = []
    rows = [r[0] for r in precedence]
    if rows != list(range(len(rows))) or len(rows) < 2:
        problems.append(f"PRECEDENCE's rows are not 0..n contiguous: {rows}")
    if set(rows) != set(MATRIX):
        problems.append(f"the page's conditions cover rows {sorted(MATRIX)}; "
                        f"PRECEDENCE has {rows}")
    branches = _branches()
    if set(branches) != set(rows):
        problems.append(f"derive_goal_state's branches mark rows {sorted(branches)}; "
                        f"PRECEDENCE has {rows}")
    for n, _cond, result in precedence:
        if n == 0:
            if not result.startswith("frozen"):
                problems.append(f"row 0's result is {result!r}; the arbiter freezes row 0")
            continue
        member = branches.get(n, (None, None))[1]
        if member != result:
            problems.append(f"row {n}: PRECEDENCE says {result}; the branch returns {member}")
        if n in SELECTORS:
            kwargs = dict(SELECTORS[n])
            kwargs["terminal_outcome"] = TerminalOutcome(kwargs["terminal_outcome"])
            got = derive_goal_state(**kwargs).name
            if got != result:
                problems.append(f"row {n}: PRECEDENCE says {result}; driven, the arbiter "
                                f"returns {got}")
    frozen = derive_goal_state(terminal_outcome=TerminalOutcome.FAILED,
                               already_recorded=GoalState.GOAL_MET)
    if frozen is not GoalState.GOAL_MET:
        problems.append("row 0: a recorded state is no longer frozen")
    return problems


def _chain_problems(authorities) -> list[str]:
    """Each chain resolves: its ADRs exist, none is SUPERSEDED, and none is superseded
    by an ADR the chain omits."""
    text = _decisions_text()
    defined = _defined_adrs(text)
    index = _index_rows(text)
    supersessions = _supersessions(text)
    problems: list[str] = []
    for heading, _o, _c, adrs, _f in authorities:
        cited: dict[int, set[int] | None] = {}
        for m in re.finditer(rf"\*\*ADR-(\d{{4}})\*\*(?:\s+{_CLAUSE})?", adrs):
            n, cl = int(m.group(1)), _clauses(m.group(2) or "")
            prev = cited.get(n, set())
            cited[n] = None if (cl is None or prev is None) else prev | cl
        if not cited:
            problems.append(f"§{heading}: the chain cites no ADR")
        for n in cited:
            if n not in defined:
                problems.append(f"§{heading}: ADR-{n:04d} does not exist")
            elif index.get(n, "").strip().upper().startswith("SUPERSEDED"):
                problems.append(f"§{heading}: ADR-{n:04d} is SUPERSEDED in the index")
        for by, old, cl in supersessions:
            if old not in cited or by in cited:
                continue
            mine = cited[old]
            if cl is not None and mine is not None and not (cl & mine):
                continue
            problems.append(f"§{heading}: cites ADR-{old:04d}, which ADR-{by:04d} supersedes, "
                            f"and does not cite ADR-{by:04d}")
    return problems


def _cell_problems() -> list[str]:
    cells = [c for a in AUTHORITIES for c in a] + [c for pair in MATRIX.values() for c in pair]
    return [f"a cell contains `|`: {c[:60]!r}" for c in cells if "|" in c]


def _check() -> list[str]:
    problems = _cell_problems() + _matrix_problems(_precedence()) + _chain_problems(AUTHORITIES)
    if "**F-" not in SECTION_5:
        problems.append("SECTION_5 carries no finding — §5 is append-only and may not be emptied")
    return problems + _pin_problems(render())


