    import importlib.util

    spec = importlib.util.spec_from_file_location("_page_stamp", pathlib.Path(__file__).with_name("_page_stamp.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


