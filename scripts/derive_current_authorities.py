def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True,
                          check=True).stdout.strip()


def _decisions_text() -> str:
    return DECISIONS.read_text(encoding="utf-8")


def _defined_adrs(text: str) -> set[int]:
    return {int(n) for n in re.findall(r"^## ADR-(\d{4})\b", text, re.M)}


def _index_rows(text: str) -> dict[int, str]:
    """ADR number → its Decision-index Status cell (and everything after it)."""
    idx = text.split("## Decision index", 1)[1] if "## Decision index" in text else ""
    rows: dict[int, str] = {}
    for line in idx.splitlines():
        m = re.match(r"^\| (\d{4}) \|", line)
        if m:
            rows[int(m.group(1))] = "|".join(line.split("|")[4:])
    return rows


def _clauses(spec: str) -> set[int] | None:
    """`R3/R7` → {3, 7}; `R6–R13` → {6..13}; no R-clause → None (the whole ADR)."""
    spec = spec.strip()
    if not spec.startswith("R"):
        return None
    out: set[int] = set()
    for part in spec.split("/"):
        m = re.fullmatch(r"R(\d+)(?:[–-]R?(\d+))?", part.strip())
        if not m:
            return None
        lo, hi = int(m.group(1)), int(m.group(2) or m.group(1))
        out.update(range(lo, hi + 1))
    return out


_CLAUSE = r"((?:R\d+(?:[–-]R?\d+)?)(?:/R\d+(?:[–-]R?\d+)?)*)"


def _supersessions(text: str) -> list[tuple[int, int, set[int] | None]]:
    """`(superseder, superseded, clauses)` from the index's Status cells."""
    out = []
    for adr, status in _index_rows(text).items():
        for m in re.finditer(rf"(?:supersedes|replaces) ADR-(\d{{4}})(?:\s+{_CLAUSE})?", status):
            out.append((adr, int(m.group(1)), _clauses(m.group(2) or "")))
    return out


def _goal_tree() -> ast.FunctionDef:
    tree = ast.parse(GOAL_PY.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == "derive_goal_state":
            return node
    raise LookupError("wisp/core/goal.py defines no derive_goal_state")


def _precedence_span() -> tuple[int, int]:
    for node in ast.parse(GOAL_PY.read_text(encoding="utf-8")).body:
        target = getattr(node, "target", None) or (getattr(node, "targets", None) or [None])[0]
        if isinstance(target, ast.Name) and target.id == "PRECEDENCE":
            return node.lineno, node.end_lineno or node.lineno
    raise LookupError("wisp/core/goal.py defines no PRECEDENCE")


def _returned_member(body: list[ast.stmt]) -> str | None:
    """The `GoalState.<member>` a branch returns, or None."""
    for stmt in body:
        if (isinstance(stmt, ast.Return) and isinstance(stmt.value, ast.Attribute)
                and isinstance(stmt.value.value, ast.Name) and stmt.value.value.id == "GoalState"):
            return stmt.value.attr
    return None


def _branches() -> dict[int, tuple[str, str | None]]:
    """Row → (pin, the `GoalState` member its branch returns), read from the AST.

    Rows 1–6 are the `if` statements carrying a `# row N` marker; row 0 is the `if` that tests
    `already_recorded`; row 7 is the function's final `return`.
    """
    fn = _goal_tree()
    lines = GOAL_PY.read_text(encoding="utf-8").splitlines()
    out: dict[int, tuple[str, str | None]] = {}
    for stmt in fn.body:
        if not isinstance(stmt, ast.If):
            continue
        names = {n.id for n in ast.walk(stmt.test) if isinstance(n, ast.Name)}
        if "already_recorded" in names:
            out[0] = (f"wisp/core/goal.py:{stmt.lineno}-{stmt.end_lineno}", None)
            continue
        m = re.search(r"#\s*row\s+(\d+)\b", lines[stmt.lineno - 1])
        if m:
            out[int(m.group(1))] = (f"wisp/core/goal.py:{stmt.lineno}",
                                    _returned_member(stmt.body))
    last = fn.body[-1]
    if isinstance(last, ast.Return):
        out[7] = (f"wisp/core/goal.py:{last.lineno}", _returned_member([last]))
    return out


